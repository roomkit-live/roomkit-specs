"""The per-rule report: each RFC unit, the scenarios citing it, and their results.

One page per top-level section under `conformance/rules/`, and an index. The
pages are generated from the RFC, the scenarios, `links.lock.json`,
`untested.json` and the execution receipts in `evidence.json`; nothing in them
is written by hand.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

from .links import Lock, citations
from .source import LEVELS, digest

DIRECTORY = "rules"
HEADER = "Generated by `check.py --traceability --update-traceability`. Do not edit."
IMPLEMENTATIONS = ("python", "rust")


def top(section: str) -> str:
    """The top-level section a numbered section belongs to: 10.4 -> 10, A.2 -> A."""
    return section.split(".")[0]


def page_name(number: str) -> str:
    return f"appendix-{number}.md" if number.isalpha() else f"section-{number}.md"


def heading(number: str, title: str) -> str:
    return f"Appendix {number}: {title}" if number.isalpha() else f"§{number} {title}"


def pages(
    registry: dict[str, Any],
    scenarios: dict[str, dict[str, Any]],
    lock: Lock,
    untested: dict[str, str],
    executions: list[dict[str, Any]],
) -> dict[str, str]:
    """Every page of the report, by file name, in a deterministic layout."""
    cited = citations(scenarios)
    states = lock_states(cited, registry, lock)
    results = latest_results(executions, scenarios)
    titles = {section["section"]: section["title"] for section in registry["sections"]}
    by_section: dict[str, list[dict[str, Any]]] = {}
    for unit in registry["requirements"]:
        by_section.setdefault(unit["section"], []).append(unit)
    tops: dict[str, list[str]] = {}
    for section in registry["sections"]:
        if section["section"] in by_section:
            tops.setdefault(top(section["section"]), []).append(section["section"])
    found = {}
    for number, sections in tops.items():
        lines = [
            f"# {heading(number, titles.get(number, ''))}",
            "",
            HEADER,
            "[All sections](README.md).",
        ]
        for section in sections:
            lines += ["", f"## {heading(section, titles[section])}", ""]
            lines += [
                "| Unit | Kind | Level | Scenario | Lock | Python | Rust |",
                "|---|---|---|---|---|---|---|",
            ]
            for unit in by_section[section]:
                lines += unit_rows(unit, cited, states, results, untested)
        found[page_name(number)] = "\n".join(lines) + "\n"
    found["README.md"] = index(tops, titles, by_section, cited, states)
    return found


def unit_rows(
    unit: dict[str, Any],
    cited: dict[str, set[str]],
    states: dict[tuple[str, str], str],
    results: dict[tuple[str, str], dict[str, str]],
    untested: dict[str, str],
) -> list[str]:
    """A unit's rows: one per citing scenario, or one saying why it has none."""
    head = f"| {unit['id']} | {unit['kind']} | {unit.get('level', '—')} |"
    names = sorted(cited.get(unit["id"], ()))
    if not names:
        reason = untested.get(unit["id"])
        cell = f"untested: {cell_text(reason)}" if reason else "—"
        return [f"{head} {cell} | | | |"]
    rows = []
    for position, name in enumerate(names):
        prefix = head if position == 0 else "| | | |"
        outcomes = [
            outcome_cell(results.get((implementation, name), {}))
            for implementation in IMPLEMENTATIONS
        ]
        rows.append(
            f"{prefix} `{name}` | {states[unit['id'], name]} | "
            f"{outcomes[0]} | {outcomes[1]} |"
        )
    return rows


def outcome_cell(by_backend: dict[str, str]) -> str:
    """`memory passed, sqlite failed`: each backend's latest outcome."""
    return ", ".join(f"{backend} {by_backend[backend]}" for backend in sorted(by_backend))


def cell_text(text: str) -> str:
    """Text kept inside one table cell."""
    return " ".join(text.split()).replace("|", "\\|")


def index(
    tops: dict[str, list[str]],
    titles: dict[str, str],
    by_section: dict[str, list[dict[str, Any]]],
    cited: dict[str, set[str]],
    states: dict[tuple[str, str], str],
) -> str:
    """The index: per top-level section, its units by level and its citations."""
    lines = [
        "# Rules and the scenarios citing them",
        "",
        HEADER,
        "",
        "Each RFC unit ([requirements.json](../requirements.json)), its level, the",
        "scenarios citing it in `requirements`, each citation's state in",
        "[links.lock.json](../links.lock.json), and the latest recorded outcome of",
        "each citing scenario per implementation and backend. A citation is not a",
        "proof: a scenario can cite a unit without covering all of it.",
        "",
        "- Level `—`: the unit has not been reviewed for its level yet.",
        "- Lock `pinned`: the scenario was read against the unit's current text;",
        "  `reread`: the unit changed since; `unpinned`: no lock entry.",
        "- An outcome counts when its receipt ran the scenario's current text,",
        "  whatever its RFC commit; the latest receipt recorded wins. Empty: no",
        "  receipt ran it.",
        "",
        "| Section | Units | must | should | may | No level | Cited units | Citations | To reread |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for number, sections in tops.items():
        units = [unit for section in sections for unit in by_section[section]]
        levels = Counter(unit.get("level") for unit in units)
        ids = {unit["id"] for unit in units}
        pairs = [state for (unit, _), state in states.items() if unit in ids]
        lines.append(
            f"| [{heading(number, titles.get(number, '')).replace('|', '/')}]"
            f"({page_name(number)}) | {len(units)} | "
            + " | ".join(str(levels[level]) for level in LEVELS)
            + f" | {levels[None]} | {sum(unit in cited for unit in ids)} | "
            f"{len(pairs)} | {pairs.count('reread')} |"
        )
    return "\n".join(lines) + "\n"


def artifacts(directory: Path, expected: dict[str, str], update: bool) -> list[str]:
    """Fail a stale or extra page unless regeneration was requested, which
    writes every page and removes the pages no longer generated."""
    folder = directory / DIRECTORY
    present = {path.name for path in folder.glob("*.md")} if folder.exists() else set()
    if update:
        folder.mkdir(exist_ok=True)
        for name, text in expected.items():
            (folder / name).write_text(text, encoding="utf-8")
        for name in sorted(present - expected.keys()):
            (folder / name).unlink()
        return []
    errors = [
        f"{DIRECTORY}/{name}: generated page differs; run --update-traceability"
        for name, text in sorted(expected.items())
        if name not in present
        or (folder / name).read_text(encoding="utf-8") != text
    ]
    errors += [
        f"{DIRECTORY}/{name}: not a generated page; run --update-traceability"
        for name in sorted(present - expected.keys())
    ]
    return errors


def lock_states(
    cited: dict[str, set[str]], registry: dict[str, Any], lock: Lock
) -> dict[tuple[str, str], str]:
    """Each citation's lock state: pinned, reread (changed since) or unpinned."""
    fingerprints = {item["id"]: item["sha256"] for item in registry["requirements"]}
    states = {}
    for unit, names in cited.items():
        for name in names:
            sha = lock.get(unit, {}).get(name)
            if sha is None:
                states[unit, name] = "unpinned"
            else:
                states[unit, name] = (
                    "pinned" if sha == fingerprints.get(unit) else "reread"
                )
    return states


def latest_results(
    executions: list[dict[str, Any]], scenarios: dict[str, dict[str, Any]]
) -> dict[tuple[str, str], dict[str, str]]:
    """Each (implementation, scenario)'s latest outcome per backend, from the
    receipts that ran the scenario's current text, whatever their RFC commit.
    Receipts are appended as they are recorded: the last one listed is the
    latest."""
    current = {name: digest(scenario) for name, scenario in scenarios.items()}
    found: dict[tuple[str, str], dict[str, str]] = defaultdict(dict)
    for run in executions:
        for result in run["results"]:
            name = result["scenario"]
            if current.get(name) == result["sha256"]:
                found[run["implementation"], name][run["backend"]] = result["outcome"]
    return dict(found)
