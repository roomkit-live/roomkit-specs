"""Deterministic coverage artifacts; mapping and runtime evidence stay distinct."""

from __future__ import annotations

from collections import Counter
from pathlib import Path
from typing import Any

from .evidence import requirement_status
from .source import digest


def build(
    registry: dict[str, Any],
    evidence: dict[str, Any],
    scenarios: dict[str, Any],
    reviews: dict[str, Any],
) -> tuple[dict[str, Any], list[str]]:
    """Generate a report, invalidating section reviews when their source moves."""
    errors = []
    inventory = {row["section"]: row for row in reviews["sections"]}
    if len(inventory) != len(reviews["sections"]):
        errors.append("duplicate section review")
    known = {section["section"] for section in registry["sections"]}
    errors += [
        f"review of unknown section {number}"
        for number in sorted(inventory.keys() - known)
    ]
    requirements = [
        requirement_status(
            item, evidence["links"], evidence, scenarios, registry["rfc_sha256"]
        )
        for item in registry["requirements"]
    ]
    sections = []
    for section in registry["sections"]:
        number = section["section"]
        review = inventory.get(number)
        if review and review["sha256"] != section["sha256"]:
            errors.append(f"§{number}: source changed since inventory review")
        if (
            review
            and review["classification"] == "normative"
            and section["unannotated_keyword_lines"]
        ):
            errors.append(
                f"§{number}: reviewed normative section has unannotated keywords"
            )
        counted = Counter(
            item["mapping"] for item in requirements if item["section"] == number
        )
        sections.append(
            {
                "section": number,
                "title": section["title"],
                "review": review["classification"] if review else "not_reviewed",
                "requirements": sum(counted.values()),
                "mapping": dict(sorted(counted.items())),
                "unannotated_keyword_lines": section["unannotated_keyword_lines"],
            }
        )
    corpus = digest(
        {name: digest(scenario) for name, scenario in sorted(scenarios.items())}
    )
    return {
        "version": 1,
        "rfc_sha256": registry["rfc_sha256"],
        "corpus_sha256": corpus,
        "python_commit": evidence["python_commit"],
        "scenario_count": len(scenarios),
        "sections": sections,
        "requirements": requirements,
    }, errors


def markdown(report: dict[str, Any]) -> str:
    """Describe the evidence, not an inferred percentage of RFC compliance."""
    rows = report["requirements"]
    mapped = sum(item["mapping"] != "unmapped" for item in rows)
    complete = sum(item["mapping"] == "mapped_complete" for item in rows)
    reviewed = sum(item["review"] != "not_reviewed" for item in report["sections"])
    lines = [
        "# Conformance traceability",
        "",
        "Generated by `check.py --traceability --update-traceability`. Do not edit.",
        "",
        f"- RFC source SHA-256: `{report['rfc_sha256']}`.",
        f"- Corpus SHA-256: `{report['corpus_sha256']}` ({report['scenario_count']} scenarios).",
        f"- Python test references at `{report['python_commit']}`.",
        "",
        f"{len(rows)} annotated source units; {mapped} have reviewed mappings, {complete} mapped as complete.",
        f"Inventory reviewed for {reviewed}/{len(report['sections'])} numbered sections.",
        "",
        "A mapping is not a passing test. A section citation is not a mapping.",
        "A source unit may contain several obligations; its scope and remaining cases matter.",
        "Execution receipts name their own RFC, corpus and implementation commits, backend and runtime.",
        "`recorded_pass` describes that receipt only; it certifies no conformance level.",
        "Unannotated keyword lines are a reading aid, not a complete list of implicit requirements.",
        "",
        "See [requirements.json](requirements.json) for exact clauses and applicability,",
        "[coverage.json](coverage.json) for each mapping and execution, and",
        "[evidence.json](evidence.json) for assertions, tests, review scope and remaining cases.",
        "",
        "| Section | Inventory review | Units | Unmapped | Partial mappings | Complete mappings | Keyword lines to review |",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for item in report["sections"]:
        counts = item["mapping"]
        lines.append(
            f"| §{item['section']} {item['title'].replace('|', '/')} | {item['review']} | "
            f"{item['requirements']} | {counts.get('unmapped', 0)} | "
            f"{counts.get('mapped_partial', 0)} | {counts.get('mapped_complete', 0)} | "
            f"{len(item['unannotated_keyword_lines'])} |"
        )
    return "\n".join(lines) + "\n"


def artifact(path: Path, expected: str, update: bool) -> list[str]:
    """Fail stale generated output unless regeneration was explicitly requested."""
    if update:
        path.write_text(expected, encoding="utf-8")
        return []
    if not path.exists() or path.read_text(encoding="utf-8") != expected:
        return [f"{path.name}: generated artifact differs; run --update-traceability"]
    return []
